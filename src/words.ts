type NonEmptyVocabulary = readonly [string, ...string[]];

/** Uniform index into a non-empty list using CSPRNG and rejection sampling. */
function pick(list: NonEmptyVocabulary): string {
  const unsignedIntegerRange = 0x1_0000_0000;
  const limit = Math.floor(unsignedIntegerRange / list.length) * list.length;
  let idx: number;
  do {
    const candidate = crypto.getRandomValues(new Uint32Array(1))[0];
    if (candidate === undefined)
      throw new Error("CSPRNG returned no candidate value");
    idx = candidate;
  } while (idx >= limit);
  const word = list[idx % list.length];
  if (word === undefined) throw new Error("Candidate vocabulary is empty");
  return word;
}

/**
 * Generate a candidate word name such as `luminescent-morel`.
 *
 * @remarks
 * This legacy helper accepts trusted sizing-policy inputs; CPU and output scale
 * with the requested count. The count uses
 * `Math.max(1, Math.floor(count ?? 2))`: `NaN`, `0`, `0.5`, `-1`, and negative
 * infinity produce one word, while `9` produces nine. Positive infinity
 * throws a bounded `RangeError`. For new durable identifiers, use
 * `defineIdFamily`.
 *
 * @param options - Candidate-name sizing and separator; bound untrusted values
 * before calling.
 * @throws If `options.count` is positive infinity.
 * @returns A candidate name assembled from the exported vocabularies.
 */
export function words(options?: {
  /** Number of words (default 2 = adjective-noun). */
  count?: number;
  /** Separator (default "-"). */
  separator?: string;
}): string {
  if (options?.count === Number.POSITIVE_INFINITY)
    throw new RangeError("words count must be finite");
  const count = Math.max(1, Math.floor(options?.count ?? 2));
  const separator = options?.separator ?? "-";
  const parts: string[] = [pick(ADJECTIVES)];
  for (let i = 1; i < count; i++) parts.push(pick(NOUNS));
  return parts.join(separator);
}
